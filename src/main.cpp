#include <iostream>
#include <vector>

// 二维热传导模拟
// Stage 2：建立数值模拟的基本参数和网格
int main() {

    // ============================================================
    // 1. 模拟区域参数
    // ============================================================

    // 金属板在 x 方向上的物理长度，单位：米
    const double length_x = 1.0;

    // 金属板在 y 方向上的物理长度，单位：米
    const double length_y = 1.0;


    // ============================================================
    // 2. 网格参数
    // ============================================================

    // x 方向上的网格点数量
    // 这里使用 51 个点，因此实际上有 50 个网格间隔
    const int nx = 51;

    // y 方向上的网格点数量
    const int ny = 51;


    // ============================================================
    // 3. 计算空间步长
    // ============================================================

    // 相邻两个网格点之间的距离
    //
    // 注意：
    // nx 个点实际上只有 nx - 1 个间隔
    //
    // 因此：
    // dx = length_x / (nx - 1)
    const double dx = length_x / (nx - 1);

    // y 方向同理
    const double dy = length_y / (ny - 1);


    // ============================================================
    // 4. 输出当前设置
    // ============================================================

    std::cout << "Heat Simulation\n";
    std::cout << "-------------------------\n";

    std::cout << "Grid: "
              << nx << " x " << ny << '\n';

    std::cout << "dx = "
              << dx << " m\n";

    std::cout << "dy = "
              << dy << " m\n";


    return 0;
}
