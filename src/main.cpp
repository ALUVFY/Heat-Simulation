#include <iostream>
#include <vector>

// 二维热传导模拟
// Stage 2：建立二维温度网格
int main() {

    // ============================================================
    // 1. 模拟区域参数
    // ============================================================

    // 金属板在 x 方向上的物理长度，单位：米
    const double length_x = 1.0;

    // 金属板在 y 方向上的物理长度，单位：米
    const double length_y = 1.0;


    // ============================================================
    // 2. 网格参数
    // ============================================================

    // x 方向上的网格点数量
    // 51 个点实际上对应 50 个网格间隔
    const int nx = 51;

    // y 方向上的网格点数量
    const int ny = 51;


    // ============================================================
    // 3. 计算空间步长
    // ============================================================

    // 相邻两个网格点之间的距离
    const double dx = length_x / (nx - 1);

    // y 方向的网格间距
    const double dy = length_y / (ny - 1);


    // ============================================================
    // 4. 温度参数
    // ============================================================

    // 金属板初始背景温度，单位：摄氏度
    const double initial_temperature = 20.0;

    // 中心热源温度，单位：摄氏度
    const double hot_temperature = 100.0;


    // ============================================================
    // 5. 创建温度网格
    // ============================================================

    // 一共有 nx × ny 个网格点
    //
    // 这里使用一维 vector 来保存二维温度场。
    //
    // 例如：
    //
    // 二维：
    //
    // (0,0) (1,0) (2,0)
    // (0,1) (1,1) (2,1)
    // (0,2) (1,2) (2,2)
    //
    // 实际存储：
    //
    // [ (0,0), (1,0), (2,0),
    //   (0,1), (1,1), (2,1),
    //   (0,2), (1,2), (2,2) ]
    //
    // 每个元素都是一个温度值。

    std::vector<double> temperature(
        nx * ny,
        initial_temperature
    );


    // ============================================================
    // 6. 找到中心位置
    // ============================================================

    // 网格中心的 x 坐标
    const int center_x = nx / 2;

    // 网格中心的 y 坐标
    const int center_y = ny / 2;


    // ============================================================
    // 7. 将中心点设置为高温
    // ============================================================

    // 将二维坐标 (center_x, center_y)
    // 转换成一维数组中的位置。
    const int center_index =
        center_x + center_y * nx;

    // 将中心点温度设置为 100 ℃
    temperature[center_index] = hot_temperature;


    // ============================================================
    // 8. 输出基本信息
    // ============================================================

    std::cout << "Heat Simulation\n";
    std::cout << "-------------------------\n";

    std::cout << "Grid: "
              << nx << " x " << ny << '\n';

    std::cout << "dx = "
              << dx << " m\n";

    std::cout << "dy = "
              << dy << " m\n";

    std::cout << "Initial temperature = "
              << initial_temperature << " C\n";

    std::cout << "Center temperature = "
              << temperature[center_index] << " C\n";


    return 0;
}

