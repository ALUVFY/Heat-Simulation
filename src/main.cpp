
#include <iostream>
#include <vector>

// ============================================================
// 二维热传导数值模拟
//
// Stage 2：建立二维温度网格和热传导基本参数
//
// 当前阶段完成：
// 1. 建立 1 m × 1 m 的二维区域
// 2. 建立 51 × 51 的计算网格
// 3. 建立温度场
// 4. 设置初始温度和中心高温点
// 5. 设置热扩散系数和时间步长
// 6. 计算显式有限差分格式中的稳定性系数 r
//
// 当前阶段暂时还没有进行真正的时间迭代。
// ============================================================


int main() {

    // ============================================================
    // 1. 模拟区域参数
    // ============================================================

    // 金属板在 x 方向上的物理长度
    // 单位：米
    const double length_x = 1.0;

    // 金属板在 y 方向上的物理长度
    // 单位：米
    const double length_y = 1.0;


    // ============================================================
    // 2. 网格参数
    // ============================================================

    // x 方向上的网格点数量
    //
    // 注意：
    // 51 个网格点实际上对应 50 个网格间隔。
    //
    // 例如：
    //
    // |----|----|----|----|
    // 0    1    2    3    4
    //
    // 5 个点只有 4 个间隔。
    const int nx = 51;

    // y 方向上的网格点数量
    const int ny = 51;


    // ============================================================
    // 3. 计算空间步长
    // ============================================================

    // x 方向相邻两个网格点之间的距离
    //
    // 因为 nx 个点只有 nx - 1 个间隔，
    // 所以：
    //
    // dx = length_x / (nx - 1)
    //
    // 当前：
    //
    // dx = 1.0 / 50
    //    = 0.02 m
    const double dx = length_x / (nx - 1);

    // y 方向同理
    //
    // dy = 1.0 / 50
    //    = 0.02 m
    const double dy = length_y / (ny - 1);


    // ============================================================
    // 4. 温度参数
    // ============================================================

    // 金属板初始背景温度
    // 单位：摄氏度
    const double initial_temperature = 20.0;

    // 中心热源温度
    // 单位：摄氏度
    const double hot_temperature = 100.0;


    // ============================================================
    // 5. 热传导参数
    // ============================================================

    // 热扩散系数
    //
    // 单位：m²/s
    //
    // 它描述材料内部温度传播的快慢。
    //
    // alpha 越大：
    //     温度传播越快
    //
    // alpha 越小：
    //     温度传播越慢
    const double alpha = 0.01;

    // 时间步长
    //
    // 单位：秒
    //
    // 每进行一次数值计算，
    // 模拟时间向前推进 dt 秒。
    const double dt = 0.005;


    // ============================================================
    // 6. 计算稳定性系数
    // ============================================================

    // 对于二维、dx = dy 的显式有限差分格式：
    //
    //     r = alpha * dt / dx²
    //
    // 稳定性条件：
    //
    //     r <= 1/4
    //
    // 当前：
    //
    //     alpha = 0.01
    //     dt    = 0.005
    //     dx    = 0.02
    //
    // 因此：
    //
    //     r = 0.01 × 0.005 / 0.02²
    //       = 0.125
    //
    // 满足：
    //
    //     0.125 <= 0.25
    //
    // 所以当前参数满足稳定性条件。
    const double r =
        alpha * dt / (dx * dx);


    // ============================================================
    // 7. 创建二维温度网格
    // ============================================================

    // 一共有：
    //
    //     nx × ny
    //
    // 个网格点。
    //
    // 当前：
    //
    //     51 × 51 = 2601
    //
    // 个温度值。
    //
    // 我们使用一维 vector 来保存二维温度场。
    //
    // 二维网格：
    //
    //     (0,0) (1,0) (2,0)
    //     (0,1) (1,1) (2,1)
    //     (0,2) (1,2) (2,2)
    //
    // 在内存中可以表示成：
    //
    //     [ (0,0), (1,0), (2,0),
    //       (0,1), (1,1), (2,1),
    //       (0,2), (1,2), (2,2) ]
    //
    // 每一个元素保存一个温度值。
    //
    // 初始化时，所有网格点温度都设置为 20 ℃。
    std::vector<double> temperature(
        nx * ny,
        initial_temperature
    );


    // ============================================================
    // 8. 找到网格中心
    // ============================================================

    // x 方向中心位置
    //
    // 51 / 2 = 25
    //
    // 因此中心点的 x 索引是 25。
    const int center_x = nx / 2;

    // y 方向中心位置
    //
    // 同样得到 25。
    const int center_y = ny / 2;


    // ============================================================
    // 9. 二维坐标转换成一维数组下标
    // ============================================================

    // 我们使用下面的公式：
    //
    //     index = i + j * nx
    //
    // 将二维坐标 (i, j)
    // 转换成一维 vector 中的位置。
    //
    // 对于中心点：
    //
    //     center_x = 25
    //     center_y = 25
    //
    // 所以：
    //
    //     center_index
    //     = 25 + 25 × 51
    //     = 1300
    const int center_index =
        center_x + center_y * nx;


    // ============================================================
    // 10. 设置中心高温点
    // ============================================================

    // 将中心点的温度从：
    //
    //     20 ℃
    //
    // 修改为：
    //
    //     100 ℃
    //
    // 现在温度场的状态大致是：
    //
    //     整个区域：20 ℃
    //
    //     中心：
    //
    //          100 ℃
    //
    // 下一阶段我们会让这个高温点向周围扩散热量。
    temperature[center_index] = hot_temperature;


    // ============================================================
    // 11. 输出模拟参数
    // ============================================================

    std::cout << "Heat Simulation\n";
    std::cout << "-------------------------\n";


    // 输出网格大小
    std::cout << "Grid: "
              << nx << " x " << ny << '\n';


    // 输出 x 方向空间步长
    std::cout << "dx = "
              << dx << " m\n";


    // 输出 y 方向空间步长
    std::cout << "dy = "
              << dy << " m\n";


    // 输出初始温度
    std::cout << "Initial temperature = "
              << initial_temperature
              << " C\n";


    // 输出中心点温度
    std::cout << "Center temperature = "
              << temperature[center_index]
              << " C\n";


    // 输出热扩散系数
    std::cout << "alpha = "
              << alpha
              << " m^2/s\n";


    // 输出时间步长
    std::cout << "dt = "
              << dt
              << " s\n";


    // 输出稳定性系数
    std::cout << "r = "
              << r
              << '\n';


    // ============================================================
    // 12. 程序正常结束
    // ============================================================

    return 0;
}

